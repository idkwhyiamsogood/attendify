//! Входные данные репозиториев (`infra/postgres`).
//!
//! Это не DTO: сюда попадают значения ровно в том виде, в каком они лежат в БД
//! (шифротекст, хеши, bidx, выбранный сервисом статус). Собирает их сервисный слой
//! из DTO запроса, репозиторий только пишет их в таблицу, ничего не вычисляя.
//!
//! `Create*Params` — все поля новой записи, кроме `id` и `created_at`/`updated_at`
//! (их проставляет репозиторий).
//! `Update*Params` — частичное обновление: `None` — поле не меняется,
//! для nullable-колонок `Some(None)` записывает `NULL`.

